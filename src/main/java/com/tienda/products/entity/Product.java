package com.tienda.products.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

import java.math.BigDecimal;

/**
 * ENTITY: Product (Model layer / JPA).
 *
 * <p>This class is the "map" between a PostgreSQL table and a Java class.
 * Hibernate reads these annotations and generates the SQL underneath
 * (INSERT, SELECT, UPDATE, DELETE).
 *
 * <p>Resulting table in PostgreSQL:
 * <pre>
 *   CREATE TABLE products (
 *       id          BIGSERIAL PRIMARY KEY,
 *       name        VARCHAR(120)  NOT NULL,
 *       description VARCHAR(500),
 *       price       NUMERIC(10,2) NOT NULL
 *   );
 * </pre>
 */
@Entity
// @Entity: marks the class as a JPA entity. Hibernate links it to a PostgreSQL table.
//           Without this annotation the class simply does not exist for the database.
@Table(name = "products")
// @Table: specifies the REAL table name in PostgreSQL.
//         If omitted, Hibernate would use the class name ("product") in the singular.
public class Product {

    /**
     * Primary key. Its value is generated by the database through a PostgreSQL sequence.
     */
    @Id
    // @Id: marks the attribute as the Primary Key of the table.
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // @GeneratedValue: delegates value generation to the database.
    // IDENTITY on PostgreSQL means a "bigserial" column: PostgreSQL creates the
    // sequence and the trigger that fills it in.
    private Long id;

    /**
     * Product name. Mandatory: it can never be null or blank when it arrives from JSON.
     */
    @Column(name = "name", nullable = false, length = 120)
    // @Column: customises the mapping towards the "name" column.
    //          nullable = false -> the column is NOT NULL in the database.
    //          length = 120     -> varchar(120) (protects against oversized input).
    private String name;

    /**
     * Optional product description. It may be null, so it has no nullable = false.
     */
    @Column(name = "description", length = 500)
    private String description;

    /**
     * Product price.
     *
     * <p>BigDecimal is used on purpose instead of double: floating point numbers have
     * rounding errors (0.1 + 0.2 != 0.3). For money you always use BigDecimal.
     */
    @Column(name = "price", nullable = false, precision = 10, scale = 2)
    // precision = 10 -> up to 10 digits in total; scale = 2 -> 2 decimal places (NUMERIC(10,2)).
    private BigDecimal price;

    /**
     * Empty constructor (no arguments).
     * Hibernate needs it to instantiate the object and set the fields via reflection.
     */
    public Product() {
        // Empty constructor required by JPA.
    }

    /**
     * Constructor with every attribute (handy to build objects in tests and in the Service).
     */
    public Product(String name, String description, BigDecimal price) {
        this.name = name;
        this.description = description;
        this.price = price;
    }

    // --- GETTERS and SETTERS ---
    // They are mandatory: Jackson (the JSON converter) uses them to serialise the object
    // and Hibernate uses them to read and write the table columns.

    /** Returns the unique identifier of the product. */
    public Long getId() {
        return id;
    }

    /** Sets the unique identifier of the product (Hibernate does it on insert). */
    public void setId(Long id) {
        this.id = id;
    }

    /** Returns the product name. */
    public String getName() {
        return name;
    }

    /** Sets the product name. */
    public void setName(String name) {
        this.name = name;
    }

    /** Returns the product description. */
    public String getDescription() {
        return description;
    }

    /** Sets the product description. */
    public void setDescription(String description) {
        this.description = description;
    }

    /** Returns the product price. */
    public BigDecimal getPrice() {
        return price;
    }

    /** Sets the product price. */
    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    /**
     * equals() and hashCode(): two products are "equal" when they share the same id.
     * This matters when products are stored in collections (List, Set) or compared in tests.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof Product)) {
            return false;
        }
        Product other = (Product) o;
        // If both ids are present, compare by id; otherwise fall back to reference equality.
        return id != null && id.equals(other.id);
    }

    @Override
    public int hashCode() {
        return id != null ? id.hashCode() : System.identityHashCode(this);
    }

    /**
     * toString(): renders the object as readable text (useful in the server logs).
     * It is called implicitly when the object is concatenated with a string.
     */
    @Override
    public String toString() {
        return "Product{id=" + id + ", name='" + name + "', price=" + price + "}";
    }
}
