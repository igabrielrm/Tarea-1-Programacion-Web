package com.tienda.products.service;

import com.tienda.products.dto.ProductRequest;
import com.tienda.products.dto.ProductResponse;

import java.util.List;

/**
 * SERVICE (contract): ProductService.
 *
 * <p>It defines WHAT the application can do with products, without the details of HOW it does it.
 *
 * <p>Why an interface? Because it separates the "what" from the "how":
 * <ul>
 *   <li>The Controller depends on this interface, not on the concrete implementation.</li>
 *   <li>In tests it can be replaced by a mock without touching the Controller.</li>
 *   <li>If tomorrow you swap JPA for another engine (Mongo, plain JDBC), you only change
 *       the implementation.</li>
 * </ul>
 */
public interface ProductService {

    /**
     * Lists every product in the database.
     *
     * @return the list of products (empty when there are none, never null).
     */
    List<ProductResponse> findAll();

    /**
     * Searches the products whose name contains the given text (case insensitive).
     *
     * @param term the text fragment to search for.
     * @return the matching products (an empty list when nothing matches).
     */
    List<ProductResponse> search(String term);

    /**
     * Finds a product by its identifier.
     *
     * @param id identifier of the product to look for.
     * @return the product that was found.
     * @throws com.tienda.products.exception.ResourceNotFoundException when it does not exist.
     */
    ProductResponse findById(Long id);

    /**
     * Creates a new product from the already validated JSON data.
     *
     * @param request the incoming data, validated by Bean Validation.
     * @return the created product, already carrying the id generated by PostgreSQL.
     * @throws com.tienda.products.exception.DuplicateResourceException when the name already exists.
     */
    ProductResponse create(ProductRequest request);

    /**
     * Updates an existing product (full update / PUT).
     *
     * @param id      identifier of the product to update.
     * @param request the new data, already validated.
     * @return the updated product.
     * @throws com.tienda.products.exception.ResourceNotFoundException when it does not exist.
     */
    ProductResponse update(Long id, ProductRequest request);

    /**
     * Deletes a product by its identifier.
     *
     * @param id identifier of the product to delete.
     * @throws com.tienda.products.exception.ResourceNotFoundException when it does not exist.
     */
    void delete(Long id);
}
